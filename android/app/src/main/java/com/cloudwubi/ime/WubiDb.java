    private static Map<String, List<String>> singleIndex;
    private static Map<String, List<String>> phraseIndex;

    private static void ensureIndex() {
        if (singleIndex != null) return;
        singleIndex = new HashMap<>();
        for (String item : SINGLE_WUBI) {
            int p = item.indexOf(':');
            if (p < 0) continue;
            String code = item.substring(0, p);
            String chars = item.substring(p + 1);
            List<String> list = new ArrayList<>();
            for (int i = 0; i < chars.length(); i++) {
                list.add(String.valueOf(chars.charAt(i)));
            }
            singleIndex.put(code, list);
        }
        phraseIndex = new HashMap<>();
        for (String item : PHRASE_WUBI) {
            int p = item.indexOf(':');
            if (p < 0) continue;
            String code = item.substring(0, p);
            String word = item.substring(p + 1);
            phraseIndex.computeIfAbsent(code, k -> new ArrayList<>()).add(word);
        }
    }

    /**
     * 查询候选（按用户固化规则排序）：
     * 1码 -> 高频单字；2码 -> 单字在前、词组在后；3码 -> 单字；4码 -> 词组优先、单字殿后
     * 返回 null 表示无命中（交由云端）
     */

    /**
     * 3码预测：返回以 code3 开头的高频4码词组（用户固化规则：三字母提示第4码词组）
     * 返回 null 表示无预测
     */
    public static List<String> queryPredict(String code3) {
        if (code3 == null || code3.length() != 3) return null;
        ensureIndex();
        List<String> result = new ArrayList<>();
        for (Map.Entry<String, List<String>> e : phraseIndex.entrySet()) {
            String c = e.getKey();
            if (c.length() == 4 && c.startsWith(code3)) {
                result.addAll(e.getValue());
            }
        }
        return result.isEmpty() ? null : result;
    }

    public static List<String> query(String code) {
        if (code == null || code.isEmpty()) return null;
        ensureIndex();
        List<String> result = new ArrayList<>();
        List<String> singles = singleIndex.get(code);
        List<String> phr = phraseIndex.get(code);
        int len = code.length();
        if (len == 1) {
            if (singles != null) result.addAll(singles);
        } else if (len == 2) {
            if (singles != null) result.addAll(singles);
            if (phr != null) result.addAll(phr);
        } else if (len == 3) {
            if (singles != null) result.addAll(singles);
        } else if (len == 4) {
            if (phr != null) result.addAll(phr);
            if (singles != null) result.addAll(singles);
        }
        return result.isEmpty() ? null : result;
    }
